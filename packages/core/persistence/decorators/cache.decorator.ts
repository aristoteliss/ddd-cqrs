const defaultLogger = consoleCacheLogger('CacheDecorator');

function errorMessage(err: unknown): string {
  return err instanceof Error ? err.message : String(err);
}

/** Why keys are evicted, for which entity, and how long a barrier lives. */
interface Eviction {
  readonly reason: CacheBarrierReason;
  readonly entity: unknown;
  readonly barrierTtl: number;
}

/**
 * Evicts one key using the strongest coordination the adapter supports.
 *
 * A {@link IVersionedCache} advances the key revision, which already fences any
 * fill that started before this mutation, so no barrier value is stored: leaving
 * one behind would make the next read hydrate a sentinel instead of a snapshot.
 * Unversioned adapters have no revision to compare, so they receive a
 * {@link CacheMutationBarrier} instead. {@link FromCache} bypasses such adapters,
 * and wherever it meets a barrier it treats it as a miss, never as a snapshot.
 */
async function evictKey(
  cache: ICache<unknown>,
  key: string,
  eviction: Eviction,
): Promise<void> {
  if (isVersionedCache(cache)) {
    await cache.invalidate(key);
    return;
  }

  const barrier = createCacheMutationBarrier(eviction.reason, eviction.entity);
  await cache.set(key, barrier, { ttl: eviction.barrierTtl });
}

/**
 * Options for configuring write-through and eviction caching via {@link Cache}.
 */
export interface CacheOptions<TEntity = unknown> {
  /**
   * Function deriving the cache key to write on success.
   * Pass `null` or omit to skip write-through caching.
   */
  setKey?: ((entity: TEntity) => string) | null;

  /**
   * Function deriving keys to evict when `save()` returns `null` or `undefined` (e.g. deletion).
   */
  deleteKeys?: ((entity: TEntity) => string[]) | null;

  /**
   * Optional secondary keys to evict on every successful save before writing the new entry.
   */
  invalidateKeys?: ((entity: TEntity) => string[]) | null;

  /**
   * Optional time-to-live in milliseconds for the write-through cache entry.
   */
  ttl?: number;

  /**
   * Optional version comparison function for CAS-safe write-through caching.
   * If omitted, defaults to {@link isCacheNewer} which compares `version`, `__gen`, or `updatedAt`.
   * Pass `null` to skip the isNewer comparison.
   */
  isNewer?: ((cached: unknown, incoming: unknown) => boolean) | null;

  /**
   * Lifetime in milliseconds of the {@link CacheMutationBarrier} written on
   * deletions and secondary invalidations.
   *
   * A barrier only has to outlive the in-flight reads/writes it guards against,
   * so configure this above the expected maximum repository operation latency.
   * Ignored by {@link IVersionedCache} adapters, which fence concurrent fills by
   * revision instead of by barrier.
   *
   * @default {@link DEFAULT_BARRIER_TTL_MS}
   */
  barrierTtl?: number;

  /**
   * Receives cache-maintenance warnings. Defaults to `console.warn` with a
   * `[CacheDecorator]` prefix. See {@link ICacheLogger}.
   */
  logger?: ICacheLogger;
}

/**
 * Default barrier lifetime: long enough to outlive an in-flight read or write
 * that started before the mutation, short enough that deleted aggregates do not
 * accumulate keys indefinitely.
 */
export const DEFAULT_BARRIER_TTL_MS = 60_000;

/**
 * Write-through cache decorator for a {@link CommandRepository} `save` method.
 *
 * Provides declarative cache synchronization on mutating database operations:
 * - **Write-through update**: When `save()` resolves with a non-nullish result, the result is cached
 *   under the key generated by `setKey` (after invalidating any secondary keys via `invalidateKeys`).
 * - **Cache eviction on delete**: When `save()` resolves with `null` or `undefined` (e.g. entity deletion),
 *   all keys returned by `deleteKeys` are evicted from the cache.
 * - **Best-effort safety**: Cache write and eviction operations swallow errors internally so that an
 *   already-committed database transaction is never converted into an application error.
 * - **Explicit keys**: Requires at least one of `setKey`, `deleteKeys` or `invalidateKeys`;
 *   scoping the key (for example with `cacheKey`) is the key function's job.
 *
 * @example Positional syntax on creation / update
 * ```typescript
 * @Cache<User, UserSnapshot>(
 *   (user) => cacheKey(User.aggregateName, { id: user.id }),
 *   null,
 *   (user) => [cacheKey(User.aggregateName, { email: user.email })],
 * )
 * async save(user: User): Promise<UserSnapshot> { ... }
 * ```
 *
 * Cache maintenance runs only after the wrapped persistence method succeeds and
 * is best-effort: cache failures are logged rather than converting an already
 * durable write into an application failure. Pair this decorator with
 * `@AcknowledgePersisted` and `@MapPersistenceErrors` in the canonical order.
 *
 * @example Options object syntax on eviction / delete
 * ```typescript
 * @Cache<User, null>({
 *   deleteKeys: (user) => [
 *     cacheKey(User.aggregateName, { id: user.id }),
 *     cacheKey(User.aggregateName, { email: user.email }),
 *   ],
 * })
 * async save(user: User): Promise<null> { ... }
 * ```
 */
export function Cache<TEntity = unknown, TResult = unknown | null>(
  setKeyOrOptions: ((entity: TEntity) => string) | CacheOptions<TEntity> | null,
  deleteKeysFn?: ((entity: TEntity) => string[]) | null,
  invalidateKeysFn?: ((entity: TEntity) => string[]) | null,
): MethodDecorator {
  const options: CacheOptions<TEntity> =
    typeof setKeyOrOptions === 'function' || setKeyOrOptions === null
      ? {
          setKey: setKeyOrOptions,
          deleteKeys: deleteKeysFn,
          invalidateKeys: invalidateKeysFn,
        }
      : setKeyOrOptions;
  if (!options || typeof options !== 'object') {
    throw new Error(
      '@Cache decorator requires an explicit key derivation function or options object.',
    );
  }

  const resolved = resolveOptions(options);
  if (!resolved.setKey && !resolved.deleteKeys && !resolved.invalidateKeys) {
    throw new Error(
      '@Cache decorator requires at least one of setKey, deleteKeys, or invalidateKeys to be specified.',
    );
  }

  return (
    _target: object,
    _propertyKey: string | symbol,
    descriptor: PropertyDescriptor,
  ) => {
    descriptor.value = wrapSave<TEntity, TResult>(
      descriptor.value,
      options,
      resolved,
    );
  };
}

/** {@link CacheOptions} with their defaults applied, once per decorator. */
interface ResolvedCacheOptions<TEntity> {
  readonly setKey: ((entity: TEntity) => string) | null;
  readonly deleteKeys: ((entity: TEntity) => string[]) | null;
  readonly invalidateKeys: ((entity: TEntity) => string[]) | null;
  readonly ttl: number | undefined;
  readonly barrierTtl: number;
  readonly logger: ICacheLogger;
  readonly isNewer:
    | ((cached: unknown, incoming: unknown) => boolean)
    | undefined;
}

/** The set key's revision and hit value, read before persistence. */
interface KeyObservation {
  readonly key: string;
  readonly revision: string;
  readonly value: unknown;
}

/** A successful save, its cache, and the key state read before the save. */
interface CacheMaintenance<TEntity> {
  readonly cache: ICache<unknown>;
  readonly entity: TEntity;
  readonly result: unknown;
  readonly observed: KeyObservation | undefined;
}

function resolveOptions<TEntity>(
  options: CacheOptions<TEntity>,
): ResolvedCacheOptions<TEntity> {
  return {
    setKey: options.setKey ?? null,
    deleteKeys: options.deleteKeys ?? null,
    invalidateKeys: options.invalidateKeys ?? null,
    ttl: options.ttl,
    barrierTtl: options.barrierTtl ?? DEFAULT_BARRIER_TTL_MS,
    logger: options.logger ?? defaultLogger,
    isNewer:
      options.isNewer === null ? undefined : (options.isNewer ?? isCacheNewer),
  };
}

function wrapSave<TEntity, TResult>(
  original: (entity: TEntity) => Promise<TResult | null>,
  options: CacheOptions<TEntity>,
  resolved: ResolvedCacheOptions<TEntity>,
) {
  return async function (
    this: CommandRepository<TEntity, unknown | null>,
    entity: TEntity,
  ): Promise<TResult | null> {
    // Observed before persistence so a write-through can tell whether anyone
    // mutated the key while this write was in flight. A versioned adapter has
    // no barrier value to outrank a late snapshot, so the revision it hands
    // out here is what keeps a deleted aggregate from being resurrected.
    const { cache } = this;
    const { setKey } = resolved;
    const observable = cache && setKey && isVersionedCache(cache);
    const observed = observable
      ? await observeKey(cache, setKey, entity)
      : undefined;

    const result = await original.call(this, entity);

    if (!this.cache) {
      reportMissingCacheProperty(this, '@Cache', options.logger);
      return result;
    }

    await maintainCache(
      { cache: this.cache, entity, result, observed },
      resolved,
    );

    return result;
  };
}

async function observeKey<TEntity>(
  cache: IVersionedCache<unknown>,
  setKey: (entity: TEntity) => string,
  entity: TEntity,
): Promise<KeyObservation | undefined> {
  try {
    const key = setKey(entity);
    const state = await cache.readState(key);
    return {
      key,
      revision: state.revision,
      value: state.status === 'hit' ? state.value : undefined,
    };
  } catch {
    return undefined;
  }
}

/**
 * Evicts the keys the save names, then writes its snapshot through unless the
 * save deleted the entity.
 */
async function maintainCache<TEntity>(
  run: CacheMaintenance<TEntity>,
  resolved: ResolvedCacheOptions<TEntity>,
): Promise<void> {
  // Cache maintenance is best-effort: the DB write already succeeded,
  // so a cache failure must not turn a success into an error.
  try {
    const deleting = run.result === null || run.result === undefined;
    const eviction: Eviction = {
      reason: deleting ? 'deleted' : 'invalidated',
      entity: run.entity,
      barrierTtl: resolved.barrierTtl,
    };
    await evictAll(run, deleting, eviction, resolved);
    if (deleting || !resolved.setKey) return;

    const setKey = setKeyOf(run.entity, resolved.setKey, resolved.logger);
    if (setKey) await writeThrough(run, setKey, resolved);
  } catch (err) {
    safeWarn(
      resolved.logger,
      `Unexpected error during cache maintenance: ${errorMessage(err)}`,
    );
  }
}

async function evictAll<TEntity>(
  run: CacheMaintenance<TEntity>,
  deleting: boolean,
  eviction: Eviction,
  resolved: ResolvedCacheOptions<TEntity>,
): Promise<void> {
  for (const key of keysToEvict(run.entity, deleting, resolved)) {
    try {
      await evictKey(run.cache, key, eviction);
    } catch (err) {
      const action = deleting ? 'evicting deletion' : 'invalidating';
      safeWarn(
        resolved.logger,
        `Failed ${action} key "${key}": ${errorMessage(err)}`,
      );
    }
  }
}

/**
 * The keys a save evicts; a key function that throws is reported and evicts
 * none.
 */
function keysToEvict<TEntity>(
  entity: TEntity,
  deleting: boolean,
  resolved: ResolvedCacheOptions<TEntity>,
): string[] {
  const keysFn = deleting ? resolved.deleteKeys : resolved.invalidateKeys;
  if (!keysFn) return [];
  try {
    return keysFn(entity) ?? [];
  } catch (err) {
    const keyOption = deleting ? 'deleteKeys' : 'invalidateKeys';
    const operation = deleting ? 'cache eviction' : 'cache maintenance';
    safeWarn(
      resolved.logger,
      `Failed resolving ${keyOption} during ${operation}: ${errorMessage(err)}`,
    );
    return [];
  }
}

/**
 * The write-through key; a key function that throws is reported and writes
 * nothing.
 */
function setKeyOf<TEntity>(
  entity: TEntity,
  setKey: (entity: TEntity) => string,
  logger: ICacheLogger,
): string | undefined {
  try {
    return setKey(entity);
  } catch (err) {
    safeWarn(
      logger,
      `Failed resolving setKey during cache maintenance: ${errorMessage(err)}`,
    );
    return undefined;
  }
}

/**
 * Writes the save's snapshot under `setKey`: `set` with `isNewer` on an
 * unversioned adapter, a fenced `tryFill` when the key's revision was observed
 * before persistence, and an invalidation otherwise.
 */
async function writeThrough<TEntity>(
  run: CacheMaintenance<TEntity>,
  setKey: string,
  resolved: ResolvedCacheOptions<TEntity>,
): Promise<void> {
  const { cache, observed } = run;
  const { ttl, isNewer } = resolved;
  try {
    const snapshot = toCacheSnapshot(run.result);
    if (!isVersionedCache(cache)) {
      await cache.set(setKey, snapshot, { ttl, isNewer });
    } else if (observed?.revision === undefined || setKey !== observed.key) {
      // No revision was observed for this key before the write, so
      // a fill cannot be fenced; drop the pre-write value instead.
      await cache.invalidate(setKey);
    } else if (!isNewer?.(observed.value, snapshot)) {
      // Skip the write-through when the snapshot observed before
      // persistence is already newer; otherwise commit it only if
      // the revision still matches, so a concurrent mutation wins.
      await cache.tryFill(setKey, observed.revision, snapshot as never, {
        ttl,
      });
    }
  } catch (err) {
    safeWarn(
      resolved.logger,
      `Failed setting cache key "${setKey}": ${errorMessage(err)}`,
    );
  }
}
